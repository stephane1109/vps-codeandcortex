# Vérification du journal de durées, y compris une interruption.
source(file.path("backend", "r", "pipeline_chronometrage.R"))
fichier <- tempfile(fileext = ".csv")
chronometre <- creer_chronometre_pipeline(fichier)
chronometre$demarrer("test", "Exécution fictive", "chd")
Sys.sleep(0.02)
chronometre$terminer("test")
d <- utils::read.csv(fichier)
stopifnot(nrow(d) == 1L, d$duree_secondes[[1]] >= 0.01)
stopifnot(all(c("cpu_utilisateur_secondes", "cpu_systeme_secondes", "debut_utc", "fin_utc") %in% names(d)))
chronometre$demarrer("test_echec", "Interruption fictive", "afc")
chronometre$fermer()
d <- utils::read.csv(fichier)
stopifnot(nrow(d) == 2L, d$statut[[2]] == "interrompue")
unlink(fichier)
cat("Chronométrage : OK\n")
